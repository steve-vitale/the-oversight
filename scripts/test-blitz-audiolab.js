// scripts/test-blitz-audiolab.js
// PROOF for the Audio Lab (blitz-audiolab).
// Asserts the Lab's item registry:
//   1. every monster in src/data/monsters.json has EXACTLY ONE labeled Lab entry
//   2. every entry has monster name + wave + derivation text + asset reference
//   3. every referenced asset file exists on disk
//   4. hooks match audio-registry.js (wave 3-5 MONSTER_SIG, wave 2 MONSTER_HOOK_W2)
//   5. synth entries name a hook that actually exists in app.js's CombatAudio
//   6. SFX entries have label + derivation + asset reference, files exist
// RED-verified: fails on pristine (no tools/audio-lab-data.js) — run
//   git stash -u? No: verify by temporarily renaming the generated file.
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const { execFileSync } = require('child_process');
const regional = require('../src/js/regional-audio');
execFileSync(process.execPath, [path.join(__dirname, 'build-audiolab-data.js'), '--check'], { cwd: ROOT, stdio: 'pipe' });

let pass = 0, fail = 0;
function ok(cond, msg) {
  if (cond) { pass++; }
  else { fail++; console.log('FAIL: ' + msg); }
}

function loadJSON(rel) {
  return JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8'));
}
function loadRegistry() {
  const src = fs.readFileSync(path.join(ROOT, 'src/js/audio-registry.js'), 'utf8');
  const mod = { exports: {} };
  new Function('module', 'exports', src)(mod, mod.exports);
  return mod.exports;
}

// --- Lab data must exist (RED on pristine) ---------------------------------
const dataPath = path.join(ROOT, 'tools/audio-lab-data.js');
ok(fs.existsSync(dataPath), 'tools/audio-lab-data.js exists (generated by scripts/build-audiolab-data.js)');
if (!fs.existsSync(dataPath)) {
  console.log('\n' + pass + ' pass, ' + fail + ' FAIL — RED (pristine: no Lab data)');
  process.exit(1);
}
const w = {};
new Function('window', fs.readFileSync(dataPath, 'utf8'))(w);
const D = w.AUDIO_LAB_DATA;
ok(D && Array.isArray(D.monsters) && Array.isArray(D.sfx), 'Lab data has monsters[] and sfx[]');

// --- Monster registry -------------------------------------------------------
const monsters = loadJSON('src/data/monsters.json');
const ids = Object.keys(monsters).map(k => monsters[k].id);
const seen = {};
let dup = 0;
for (const e of D.monsters) { if (seen[e.id]) dup++; seen[e.id] = 1; }
ok(dup === 0, 'no duplicate monster Lab entries (dupes: ' + dup + ')');
for (const id of ids) {
  ok(!!seen[id], 'every monster has a Lab entry: ' + id);
}
ok(D.monsters.length === ids.length,
  'exactly one entry per monster (' + D.monsters.length + ' entries vs ' + ids.length + ' monsters)');

const byId = {};
for (const k of Object.keys(monsters)) byId[monsters[k].id] = monsters[k];
const registry = loadRegistry();
const appSrc = fs.readFileSync(path.join(ROOT, 'src/js/app.js'), 'utf8');
function synthExists(hook) {
  return typeof regional.specs[hook] === 'object' || appSrc.includes('function ' + hook + '(') || appSrc.includes('\n      ' + hook + '(');
}

for (const e of D.monsters) {
  const m = byId[e.id];
  ok(!!e.name && e.name === m.name, e.id + ': name matches monsters.json');
  ok(e.wave === m.wave, e.id + ': wave matches monsters.json (' + e.wave + ')');
  ok(typeof e.why === 'string' && e.why.length >= 40,
    e.id + ': derivation text present and substantive (' + (e.why || '').length + ' chars)');
  ok(['real', 'synth', 'gap'].includes(e.origin), e.id + ': origin is real|synth|gap');
  const hasFile = e.files && e.files.length > 0;
  const hasSynth = !!e.synth;
  ok(hasFile || hasSynth, e.id + ': has an asset reference (file or synth hook)');
  for (const f of (e.files || [])) {
    ok(fs.existsSync(path.join(ROOT, f)), e.id + ': asset file exists on disk: ' + f);
  }
  if (hasSynth) ok(synthExists(e.synth), e.id + ': synth hook exists in app.js: ' + e.synth);
  if (e.wave >= 3) {
    ok(registry.monsterSig[e.id] === e.hook,
      e.id + ': hook matches audio-registry MONSTER_SIG (' + e.hook + ')');
  }
  if (e.wave === 2) {
    ok(registry.monsterHookW2[e.id] === e.hook,
      e.id + ': hook matches audio-registry MONSTER_HOOK_W2 (' + e.hook + ')');
  }
}

// --- SFX --------------------------------------------------------------------
let sfxDup = 0; const sseen = {};
for (const e of D.sfx) { if (sseen[e.id]) sfxDup++; sseen[e.id] = 1; }
ok(sfxDup === 0, 'no duplicate SFX entries');
ok(D.sfx.length >= 20, 'SFX set is comprehensive (' + D.sfx.length + ' items)');
for (const e of D.sfx) {
  ok(!!e.label, 'sfx ' + e.id + ': has label');
  ok(typeof e.why === 'string' && e.why.length >= 20, 'sfx ' + e.id + ': has derivation text');
  const hasFile = e.files && e.files.length > 0;
  ok(hasFile || !!e.synth, 'sfx ' + e.id + ': has asset reference');
  for (const f of (e.files || [])) {
    ok(fs.existsSync(path.join(ROOT, f)), 'sfx ' + e.id + ': asset file exists: ' + f);
  }
  if (e.synth) ok(synthExists(e.synth), 'sfx ' + e.id + ': synth hook exists in app.js: ' + e.synth);
}

// --- Lab page exists and loads the data --------------------------------------
ok(fs.existsSync(path.join(ROOT, 'tools/audio-lab.html')), 'tools/audio-lab.html exists');
const html = fs.readFileSync(path.join(ROOT, 'tools/audio-lab.html'), 'utf8');
ok(html.includes('audio-lab-data.js'), 'Lab page loads the registry data');
const offlinePlan = require('./build-offline-assets').update(ROOT, true);
const regionalUrls = offlinePlan.scripts.filter(u => u.split('?')[0] === './src/js/regional-audio.js');
ok(regionalUrls.length === 1 && offlinePlan.assets.includes(regionalUrls[0]), 'exact current shared game voice dependency URL is precached');
ok(html.includes('<div class="filterbar">') && /\.filterbar\s*\{[^}]*position:sticky/.test(html) && !/\.filters\s*\{[^}]*position:sticky/.test(html), 'one sticky filter container prevents overlapping mobile filter rows');

const proof = execFileSync(process.execPath, [path.join(__dirname, 'test-regional-audio.js')], { cwd: ROOT, env: process.env, encoding: 'utf8', maxBuffer: 2e6 });
process.stdout.write(proof);
ok(/regional-audio proof green:/.test(proof), 'shared renderer and real game audio emission proof is mandatory');
console.log('\n' + pass + ' pass, ' + fail + ' fail');
process.exit(fail ? 1 : 0);
