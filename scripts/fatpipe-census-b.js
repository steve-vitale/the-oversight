#!/usr/bin/env node
// scripts/fatpipe-census-b.js — RENDER/FAT PIPELINE CENSUS (flesh-out loop B,
// 2026-10-17, arm sim-renderfat-b, the camptasks-b named next "sim-fatpipe-b").
//
// Diagnostic audit of the render/fat pipeline on the courtship substrate
// (FEASTSCALE_R13=1, SEATDRIVE=0 EXPLICIT, 8 fresh seeds x
// {leadfeast,belongfeast}, 180d death-aware via runDays engine tail).
//
// Canon (docs/PRESERVATION.md, docs/BEAR.md, read twice): the ladder is
// cleaned < cooked < smoked < rendered fat (90d) < pemmican (120d); raw fat
// -> rendered tallow over fire (12 ticks, 0.90x known / 0.65x blind — the
// attempt teaches); pemmican needs render knowledge; separable fat is
// animal-specific (bear 6 slabs, boar 3, javelina 2; ~20% of gross).
//
// Pre-registered census questions (see evidence/2026-10-17/sim-renderfat-b.md):
//   Q1 engagement: renderFat firings (actor/container), makePemmican firings.
//   Q2 stocks: fat slabs generated by butchering (both generation sites),
//       by species; fat-bearing carcasses presented for cleaning.
//   Q3 gates: days the village knows 'render', Tallow & Keeping book seen,
//       fire availability on fat-holding days.
//   Q4 spoilage: raw-fat rot events (beats) + ledger fate.
//   Q5 pemmican: firings, bars, kcal.
//   Q6 pantry kcal: rendered-fat kcal per container over time.
// BAR: 100% attribution — every generated fat slab ends in exactly one of
//   rendered | rotted | pemmican-consumed | end-stock | missing (residual).
//
// INSTRUMENT HONESTY: wraps are read-only (identity Map + counters only,
// zero RNG draws, zero writes to game state — the ledger lives in a side
// Map keyed by item object). The det-gate in scripts/test-renderfat-b.js
// proves byte-identical trajectories (instrument on vs off).
//
// ZERO src/js, ZERO scripts/policies edits. Usage:
//   FEASTSCALE_R13=1 SEATDRIVE=0 node scripts/fatpipe-census-b.js
// Targeted: SEEDS="7911" POLICIES="leadfeast" DAYS=60 SMOKE=1 ...
'use strict';
const fs = require('fs');
const path = require('path');
const { belongfeast, leadfeast } = require('./policies/feastscale');
const { loadGame, setupGame, runDays, quietLog } = require('./sim-harness');
const census = require('./camptask-census-b');

const SEEDS = (process.env.SEEDS ? process.env.SEEDS.split(',').map(s => parseInt(s.trim(), 10)) : [7911, 7912, 7913, 7914, 7915, 7916, 7917, 7918]).filter(Number.isFinite);
const POLICIES = (process.env.POLICIES ? process.env.POLICIES.split(',').map(s => s.trim()) : ['leadfeast', 'belongfeast']);
const DAYS = parseInt(process.env.DAYS || '180', 10);
const SMOKE = process.env.SMOKE === '1';
const EFF_DAYS = SMOKE ? 12 : DAYS;
const EVID = path.join(__dirname, '..', 'evidence', '2026-10-17', 'perseed-fatpipe');
const RANK_ORDER = { village: 0, regional: 1, national: 2, global: 3 };

const gday = (Game) => { try { return (Game.state.scholar || {}).day || 0; } catch (e) { return 0; } };
const num = (x) => (typeof x === 'number' && Number.isFinite(x) ? x : null);
const isFat = (it) => !!(it && it.foodKind === 'fat');
const isRawFat = (it) => isFat(it) && it.foodState === 'raw';
const isRenderedFat = (it) => isFat(it) && it.foodState === 'rendered';
const fatSpecies = (it) => String((it && it.plantId) || '').replace(/^fat_/, '') || 'unknown';

// The shared classifyActor only knows the camptask proof's filename as
// 'fixture'. This wrapper extends it to this arm's proof file —
// self-contained here, zero changes to the sibling's landed instrument.
function classifyFatActor() {
  const a = census.classifyActor();
  if (a !== 'fixture') {
    try {
      const st = new Error().stack || '';
      if (/test-renderfat-b\.js/.test(st)) return 'fixture';
    } catch (e) {}
  }
  return a;
}

function containersOf(Game) {
  const out = [];
  try { const inv = Game.state.scholar.inventory || []; out.push(['pack', inv]); } catch (e) {}
  try { const st = Game.prepStash ? Game.prepStash() : null; if (st) out.push(['stash', st]); } catch (e) {}
  try { const pan = (Game.state.village || {}).pantry; if (pan) out.push(['pantry', pan]); } catch (e) {}
  return out;
}
function containerName(Game, c) {
  for (const [n, arr] of containersOf(Game)) if (arr === c) return n;
  return 'other';
}

// ---- the fat ledger: object identity -> lifecycle record (side Map only) ----
function attachFatInstrument(Game, t) {
  t.ledger = new Map(); // item object -> record
  t.renderEvents = [];
  t.pemmicanEvents = [];
  t.rotEvents = [];
  t.genEvents = [];
  t.genSeq = 0;
  t.errors = t.errors || 0;

  function scanForGenerations(container, via) {
    try {
      const label = containerName(Game, container);
      const fresh = [];
      for (const it of (container || [])) if (isFat(it) && !t.ledger.has(it)) fresh.push(it);
      if (fresh.length) {
        // attribute the generation call
        const actor = classifyFatActor();
        for (const it of fresh) {
          const slabs = it.units || 1;
          const rec = {
            id: ++t.genSeq, day: gday(Game), via, container: label, actor,
            species: fatSpecies(it), name: String(it.name || 'fat'),
            slabs, hiddenKcalEach: num(it.hiddenKcal) || 0,
            fate: null, fateDay: null, renderedKcalEach: null,
          };
          t.ledger.set(it, rec);
          t.genEvents.push({ day: rec.day, via, container: label, actor, species: rec.species, slabs, hiddenKcalEach: rec.hiddenKcalEach });
        }
      }
    } catch (e) { t.errors++; }
  }

  // 1. generation site 1: carcassToMeat (self-butcher via cleanCarcass AND
  //    the Field Dress ability — actor classification separates them).
  try {
    if (typeof Game.carcassToMeat === 'function') {
      const orig = Game.carcassToMeat.bind(Game);
      Game.carcassToMeat = function (inv, i, knows) {
        let out = null, err = null;
        try { out = orig(inv, i, knows); } catch (e) { err = e; }
        try { scanForGenerations(inv, 'carcassToMeat'); } catch (e) { t.errors++; }
        if (err) throw err;
        return out;
      };
    } else t.errors++;
  } catch (e) { t.errors++; }

  // 2. generation site 2: askSpecialist (specialist butcher).
  try {
    if (typeof Game.askSpecialist === 'function') {
      const orig = Game.askSpecialist.bind(Game);
      Game.askSpecialist = function (vid, idx, container, forceTask) {
        let out = null, err = null;
        try { out = orig(vid, idx, container, forceTask); } catch (e) { err = e; }
        try {
          const inv = container || Game.state.scholar.inventory;
          scanForGenerations(inv, 'specialist');
        } catch (e) { t.errors++; }
        if (err) throw err;
        return out;
      };
    } else t.errors++;
  } catch (e) { t.errors++; }

  // 3. render events: wrap renderFat, capture raw->rendered transitions.
  try {
    if (typeof Game.renderFat === 'function') {
      const orig = Game.renderFat.bind(Game);
      Game.renderFat = function (idx, container) {
        const actor = classifyFatActor();
        const day = gday(Game);
        let knowsBefore = false;
        try { knowsBefore = !!Game.knowsTechnique('render'); } catch (e) {}
        const inv = container || Game.state.scholar.inventory;
        const before = [];
        try { for (const it of (inv || [])) if (isRawFat(it)) before.push(it); } catch (e) {}
        let out = null, err = null;
        try { out = orig(idx, container); } catch (e) { err = e; }
        try {
          let n = 0, kcal = 0;
          for (const it of before) {
            if (isRenderedFat(it)) {
              n += (it.units || 1);
              kcal += (num(it.kcalEach) || 0) * (it.units || 1);
              let rec = t.ledger.get(it);
              if (!rec) {
                // generation wraps missed this item — register it here so the
                // render attribution stays exact (via 'render-catch').
                rec = {
                  id: ++t.genSeq, day, via: 'render-catch', container: containerName(Game, inv), actor,
                  species: fatSpecies(it), name: String(it.name || 'fat'),
                  slabs: it.units || 1, hiddenKcalEach: null,
                  fate: null, fateDay: null, renderedKcalEach: null,
                };
                t.ledger.set(it, rec);
                t.genEvents.push({ day, via: 'render-catch', container: rec.container, actor, species: rec.species, slabs: rec.slabs, hiddenKcalEach: null });
              }
              rec.fate = 'rendered'; rec.fateDay = day; rec.renderedKcalEach = num(it.kcalEach);
            }
          }
          t.renderEvents.push({ day, actor, container: containerName(Game, inv), slabs: n, kcalOut: Math.round(kcal), blind: !knowsBefore, threw: !!err });
        } catch (e) { t.errors++; }
        if (err) throw err;
        return out;
      };
    } else t.errors++;
  } catch (e) { t.errors++; }

  // 4. pemmican events: wrap makePemmican, count sets fired + rendered-fat consumed.
  try {
    if (typeof Game.makePemmican === 'function') {
      const orig = Game.makePemmican.bind(Game);
      Game.makePemmican = function (container) {
        const actor = classifyFatActor();
        const day = gday(Game);
        const inv = container || Game.state.scholar.inventory;
        let setsBefore = 0;
        try { setsBefore = Game.pemmicanSets ? Game.pemmicanSets(inv) : 0; } catch (e) {}
        const renderedBefore = [];
        try { for (const it of (inv || [])) if (isRenderedFat(it)) renderedBefore.push({ it, units: it.units || 1 }); } catch (e) {}
        let out = null, err = null;
        try { out = orig(container); } catch (e) { err = e; }
        try {
          let consumedSlabs = 0;
          for (const { it, units } of renderedBefore) {
            const now = (it.units || 1);
            const stillThere = (inv || []).includes(it) && isRenderedFat(it);
            const gone = stillThere ? Math.max(0, units - now) : units;
            if (gone > 0) {
              consumedSlabs += gone;
              const rec = t.ledger.get(it);
              if (rec && rec.fate === 'rendered') { rec.fate = 'pemmican'; rec.fateDay = day; }
            }
          }
          t.pemmicanEvents.push({ day, actor, container: containerName(Game, inv), sets: setsBefore, consumedRenderedSlabs: consumedSlabs, threw: !!err });
        } catch (e) { t.errors++; }
        if (err) throw err;
        return out;
      };
    } else t.errors++;
  } catch (e) { t.errors++; }

  // 5. rot beats: the overnight sweep names rotted items.
  //    "Overnight, A; B went bad — beyond saving." (food.js)
  try {
    const oSay = Game.say ? Game.say.bind(Game) : null;
    if (!oSay) { t.errors++; return; }
    const strip = (s) => String(s == null ? '' : s).replace(/<[^>]*>/g, '').replace(/\s+/g, ' ').slice(0, 600);
    Game.say = function (msg) {
      try {
        const s = strip(msg);
        const m = s.match(/^Overnight, (.+?) went bad [—-] beyond saving/);
        if (m) {
          const day = gday(Game);
          for (const seg of m[1].split(';')) {
            const name = seg.trim();
            if (!/fat \(raw\)/i.test(name)) continue;
            // match the most recent unaccounted ledger record with this name
            let best = null;
            for (const rec of t.ledger.values()) {
              if (rec.name === name && !rec.fate) { if (!best || rec.day > best.day) best = rec; }
            }
            if (best) { best.fate = 'rotted'; best.fateDay = day; best.rotName = name; }
            t.rotEvents.push({ day, name, matched: !!best });
          }
        }
      } catch (e) { t.errors++; }
      return oSay(msg);
    };
    t._oSay = oSay;
  } catch (e) { t.errors++; }
}

// ---- daily sampling ----
function fatPoolSnapshot(Game) {
  const snap = { rawSlabs: 0, rawKcalHidden: 0, renderedSlabs: 0, renderedKcal: 0, byContainer: {} };
  try {
    for (const [label, arr] of containersOf(Game)) {
      let rs = 0, rk = 0, ds = 0, dk = 0;
      for (const it of (arr || [])) {
        if (isRawFat(it)) { rs += (it.units || 1); rk += (num(it.hiddenKcal) || 0) * (it.units || 1); }
        else if (isRenderedFat(it)) { ds += (it.units || 1); dk += (num(it.kcalEach) || 0) * (it.units || 1); }
      }
      snap.rawSlabs += rs; snap.rawKcalHidden += rk;
      snap.renderedSlabs += ds; snap.renderedKcal += dk;
      snap.byContainer[label] = { rawSlabs: rs, rawKcalHidden: Math.round(rk), renderedSlabs: ds, renderedKcal: Math.round(dk) };
    }
  } catch (e) {}
  snap.rawKcalHidden = Math.round(snap.rawKcalHidden);
  snap.renderedKcal = Math.round(snap.renderedKcal);
  return snap;
}
function fatBearingCarcasses(Game) {
  // kill-side input to the ladder: carcasses of fat-yielding species in containers.
  let n = 0, kcal = 0;
  try {
    const animals = Game.data.animals || [];
    for (const [, arr] of containersOf(Game)) {
      for (const it of (arr || [])) {
        if (!it || it.foodState !== 'carcass') continue;
        const aid = String(it.plantId || '').replace(/^meat_/, '');
        const adef = animals.find(a => a.id === aid) || {};
        if ((adef.butcher || {}).fat > 0) { n++; kcal += (num(it.hiddenKcal) || num(it.kcalEach) || 0) * (it.units || 1); }
      }
    }
  } catch (e) {}
  return { count: n, kcal: Math.round(kcal) };
}

async function oneRun(seed, policyId) {
  const base = policyId === 'leadfeast' ? leadfeast : belongfeast;
  const { Game } = await loadGame({ seed, mode: 'fatpipe-census', fullTelemetry: false });
  await setupGame(Game);
  const policy = Object.assign({}, base);
  const t = { errors: 0 };
  census.attachBeatRing(Game, t);
  attachFatInstrument(Game, t);
  census.attachDeathInstrument(Game, t);
  const hist = { maxRank: 0, table: false, exiled: false, starvedDays: 0, maxArc: 1, maxWave: 1, leanDays: 0 };
  const leanSamples = [];
  const knowSeries = [];
  let lastKnown = null;
  const oDaily = base.daily;
  policy.daily = (G, ctx) => {
    try {
      const day = (G.state.scholar || {}).day || 0;
      const pg = G.progState ? G.progState() : {};
      if (pg.tableWaiting || pg.tableDone) hist.table = true;
      let rank = 'village';
      try { rank = (G.scaleRank ? G.scaleRank() : 'village') || 'village'; } catch (e) {}
      hist.maxRank = Math.max(hist.maxRank, RANK_ORDER[rank] || 0);
      if ((G.state.scholar || {}).exiled) hist.exiled = true;
      if ((((G.state || {}).village || {}).hungryDays || 0) > 0) hist.starvedDays++;
      try { const a = (((G.state || {}).scholar || {}).prog || {}).arc || 1; if (a > hist.maxArc) hist.maxArc = a; } catch (e) {}
      try { const w = G.unlockedWave ? (G.unlockedWave() | 0) : 1; if (w > hist.maxWave) hist.maxWave = w; } catch (e) {}
      // knowledge + fire + pools
      let knows = false, book = false, fire = null;
      try { knows = !!G.knowsTechnique('render'); } catch (e) {}
      try { book = ((G.state.scholar || {}).inventory || []).some(i => i && i.bookId === 'tallow_and_keeping'); } catch (e) {}
      try { fire = !!G.nearFire(); } catch (e) { fire = null; }
      if (knows !== lastKnown) { knowSeries.push({ day, knows }); lastKnown = knows; }
      const snap = fatPoolSnapshot(G);
      const carc = fatBearingCarcasses(G);
      // safety net: any fat item never seen through the generation wraps is
      // registered here (via 'scan-safety') so the ledger covers every fat
      // item that ever exists — the 100%-attribution bar is then meaningful.
      try {
        for (const [label, arr] of containersOf(G)) {
          for (const it of (arr || [])) {
            if ((it.foodKind === 'fat') && !t.ledger.has(it)) {
              const rec = {
                id: ++t.genSeq, day, via: 'scan-safety', container: label, actor: 'scan-safety',
                species: String((it.plantId || '').replace(/^fat_/, '')) || 'unknown',
                name: String(it.name || 'fat'),
                slabs: it.units || 1, hiddenKcalEach: (typeof it.hiddenKcal === 'number' ? it.hiddenKcal : 0),
                fate: null, fateDay: null, renderedKcalEach: null,
              };
              t.ledger.set(it, rec);
              t.genEvents.push({ day, via: 'scan-safety', container: label, actor: 'scan-safety', species: rec.species, slabs: rec.slabs, hiddenKcalEach: rec.hiddenKcalEach });
            }
          }
        }
      } catch (e) { t.errors++; }
      try {
        const cap = G.kcalCap ? G.kcalCap() : 2500;
        if (((G.state.scholar || {}).kcal || 0) < 0.5 * cap) {
          hist.leanDays++;
          leanSamples.push(Object.assign({ day, scholarKcal: Math.round(num((G.state.scholar || {}).kcal) || 0), fireNearby: fire, knowsRender: knows, fatCarcasses: carc.count, fatCarcassKcal: carc.kcal }, snap));
        }
      } catch (e) { t.errors++; }
    } catch (e) { t.errors++; }
    if (oDaily) { try { return oDaily(G, ctx); } catch (e) { return undefined; } }
    return undefined;
  };
  let result;
  await quietLog(async () => { result = await runDays(Game, policy, { days: EFF_DAYS, sampleEvery: 30 }); });
  const days = num(result && result.days);
  // terminal fate classification for every ledger record
  const fates = { rendered: 0, rotted: 0, pemmican: 0, endStock: 0, missing: 0 };
  const fateSlabs = { rendered: 0, rotted: 0, pemmican: 0, endStock: 0, missing: 0 };
  try {
    const present = new Set();
    for (const [, arr] of containersOf(Game)) for (const it of (arr || [])) if (isFat(it)) present.add(it);
    for (const [it, rec] of t.ledger) {
      if (!rec.fate) rec.fate = present.has(it) ? 'endStock' : 'missing';
      fates[rec.fate] = (fates[rec.fate] || 0) + 1;
      fateSlabs[rec.fate] = (fateSlabs[rec.fate] || 0) + (rec.slabs || 0);
    }
  } catch (e) { t.errors++; }
  const genBySpecies = {};
  for (const g of t.genEvents) {
    const k = `${g.species}|${g.via}`;
    genBySpecies[k] = (genBySpecies[k] || 0) + g.slabs;
  }
  const renderSlabs = t.renderEvents.reduce((a, e) => a + (e.slabs || 0), 0);
  const renderKcal = t.renderEvents.reduce((a, e) => a + (e.kcalOut || 0), 0);
  const out = {
    schema: 'fatpipe-census-b/1', seed, policy: policyId, days, errors: t.errors,
    genEvents: t.genEvents, genBySpecies,
    genSlabs: t.genEvents.reduce((a, e) => a + (e.slabs || 0), 0),
    genKcalHidden: Math.round(t.genEvents.reduce((a, e) => a + (e.hiddenKcalEach || 0) * (e.slabs || 0), 0)),
    renderEvents: t.renderEvents, renderSlabs, renderKcal,
    pemmicanEvents: t.pemmicanEvents,
    rotEvents: t.rotEvents,
    fates, fateSlabs,
    knowSeries, leanDays: hist.leanDays, leanSamples,
    deaths: t.deaths, beats: t.beats,
    wall: { maxRank: hist.maxRank, table: hist.table, exiled: hist.exiled, starvedDays: hist.starvedDays, maxArc: hist.maxArc, maxWave: hist.maxWave },
  };
  out.schemaClean = !!(out.genEvents && out.renderEvents && out.pemmicanEvents && out.rotEvents && out.leanSamples && out.deaths && out.beats && out.wall)
    && out.genEvents.every(e => e.actor && e.day != null)
    && out.renderEvents.every(e => e.actor && e.day != null);
  out.unattributed = out.genEvents.filter(e => e.actor === 'unknown').length + out.renderEvents.filter(e => e.actor === 'unknown').length;
  return out;
}

async function main() {
  fs.mkdirSync(EVID, { recursive: true });
  const rows = [];
  for (const pid of POLICIES) {
    for (const seed of SEEDS) {
      const r = await oneRun(seed, pid);
      const fn = `${pid}-${seed}.json`;
      fs.writeFileSync(path.join(EVID, fn), JSON.stringify(r, null, 1));
      rows.push(r);
      console.log(`${pid}-${seed}: days=${r.days} genSlabs=${r.genSlabs} renderSlabs=${r.renderSlabs} fates=${JSON.stringify(r.fateSlabs)} errors=${r.errors} unattributed=${r.unattributed} schemaClean=${r.schemaClean}`);
    }
  }
  const sum = (f) => rows.reduce((a, r) => a + (r[f] || 0), 0);
  console.log('\n=== corpus (16 runs) ===');
  console.log(`  genSlabs=${sum('genSlabs')} genKcalHidden=${sum('genKcalHidden')}`);
  console.log(`  renderSlabs=${sum('renderSlabs')} renderKcal=${sum('renderKcal')}`);
  console.log(`  pemmicanFirings=${rows.reduce((a, r) => a + r.pemmicanEvents.length, 0)}`);
  const fs_ = { rendered: 0, rotted: 0, pemmican: 0, endStock: 0, missing: 0 };
  for (const r of rows) for (const k of Object.keys(fs_)) fs_[k] += (r.fateSlabs[k] || 0);
  console.log(`  fateSlabs=${JSON.stringify(fs_)}`);
  const bySp = {};
  for (const r of rows) for (const [k, v] of Object.entries(r.genBySpecies)) bySp[k] = (bySp[k] || 0) + v;
  console.log('  genBySpecies|via:');
  for (const k of Object.keys(bySp).sort((a, b) => bySp[b] - bySp[a])) console.log(`    ${k}: ${bySp[k]} slabs`);
  const known = rows.filter(r => r.knowSeries.some(s => s.knows)).length;
  console.log(`  runs ever knowing render: ${known}/16`);
  const wall = { national: 0, table: 0, maxWave4: 0, maxWave5: 0 };
  for (const r of rows) {
    if (r.wall.maxRank >= 2) wall.national++;
    if (r.wall.table) wall.table++;
    if (r.wall.maxWave >= 4) wall.maxWave4++;
    if (r.wall.maxWave >= 5) wall.maxWave5++;
  }
  console.log(`  wall: national=${wall.national} table=${wall.table} wave4=${wall.maxWave4} wave5=${wall.maxWave5}`);
  const err = rows.filter(r => r.errors > 0 || !r.schemaClean);
  console.log(`  errors/schemaDirty: ${err.length}/16`);
}

if (require.main === module) {
  main().catch(e => { console.error('FATAL', e); process.exit(1); });
}

