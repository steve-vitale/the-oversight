'use strict';
// Exercise the visible action catalog and actual renderer, including paid healing.
const K = require('./lib'), T = K.reporter('ability-wording');
(async () => {
  const G = await K.load({seed:Number(process.env.SEED || 7)});
  K.newRun(G);
  const s = G.state.scholar; s.health = 40; s.kcal = 2400;
  G.learnSkill('wound_care', 2, 'prepared wording proof');
  const medicine = () => G.activatableAbilities().find(a => a.id === 'field_medicine');
  T.ok('ordinary treatment states effect, cadence and full price without unrelated wounds', /20 HP/.test(medicine().desc) && /each part of the day/.test(medicine().desc) && /140 kcal/.test(medicine().desc) && !/Price|missing mass|knit/.test(medicine().desc), medicine().desc);
  s.prog = s.prog || {}; s.prog.feastSurge = 1.5;
  G.grantFeastBuff({quality:1,served:[{itemId:'foraged_food',kcal:1800}],guests:['a','b','c']});
  G.driveOffFeastDraw();
  T.ok('live treatment description includes the actual additive feast bonus', /30 HP/.test(medicine().desc) && /20 treatment \+ 10 feast bonus/.test(medicine().desc), medicine().desc);
  const says = K.captureSays(G), kcal = s.kcal, health = s.health;
  G.activateAbility('field_medicine');
  T.ok('final result states the actual healed amount and entire bill', s.health-health === 30 && kcal-s.kcal === 140 && /restored 30 HP.*−140 kcal/.test(says.at(-1)), says.at(-1));
  s.bloodPriceWound = 20;
  T.ok('the wound limitation appears when the bearer actually has it', /Cannot restore maximum HP lost to Blood Price/.test(medicine().desc));
  s.bloodPriceWound = 0;
  s.abilities = [];
  for (const id of ['purify','herbal_remedy','green_thumb','static_toss','cheese_wheel','bird_strike','tripwire','turncoat','freeze_tag']) K.giveAbility(G,id,{force:true});
  const noncombat = G.activatableAbilities();
  T.ok('Purify correctly describes magic rather than mundane supplies', /magic/.test(noncombat.find(a=>a.id==='purify').desc) && !/charcoal/i.test(noncombat.find(a=>a.id==='purify').desc));
  T.ok('noncombat actions retain their authored description', noncombat.filter(a=>a.abilityId==='green_thumb' && a.actionId).every(a=>a.desc.length>15));
  K.fight(G,'hushwolf');
  const combat = G.activatableAbilities();
  const described = combat.filter(a=>['static_toss','cheese_wheel','bird_strike','tripwire','turncoat','freeze_tag'].includes(a.abilityId));
  T.ok('all six combat actions with desc fields expose their effect', described.length === 6 && described.every(a=>a.desc.length>15 && !/\[\d+,\s*\d+\]/.test(a.desc)), described.map(a=>a.desc).join(' | '));
  const source = K.readSrc('src/js/app.js');
  const actual = source.match(/  function abilityBarHTML\(\) \{[\s\S]*?\r?\n  \}/)?.[0];
  if (!actual) throw Error('Actual action renderer missing');
  const esc = value => String(value).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'})[c]);
  const html = Function('Game','esc',actual+'\nreturn abilityBarHTML();')(G,esc);
  T.ok('actual action buttons show effect text without unexplained role labels', html.includes('ctx-desc') && !html.includes('ab-role') && described.every(a=>html.includes(esc(a.desc))));
  T.ok('feast status contains readable text rather than escaped markup', !/<[^>]*>/.test(G.feastedLine()) && /damage ×/.test(G.feastedLine()), G.feastedLine());
  K.newRun(G);
  G.state.scholar.abilities=[];G.state.codex.skills={};G.state.scholar.kcal=2400;
  K.giveAbility(G,'trophy_room',{force:true});
  G.state.villageSlain={hushwolf:1};
  const trophySays=K.captureSays(G), BA=globalThis.Scattering.buildarounds;
  G.useAbility('trophy_room','mark','hushwolf');
  const foe={monsterId:'hushwolf'};
  T.ok('real single-Hunter mark reports the same 25% used by damage', BA.trophyMult(G,foe)===1.25 && trophySays.some(s=>/Trophy Room:.*\+25%/.test(s)));
  K.giveAbility(G,'tracker',{level:3,force:true});
  G.useAbility('trophy_room','mark','hushwolf');
  T.ok('real assembled Hunter mark reports its actual 50% bonus', BA.trophyMult(G,foe)===1.5 && trophySays.some(s=>/Trophy Room:.*\+50%/.test(s)));
  T.done();
})().catch(e=>{console.error(e.stack);process.exitCode=1;});
