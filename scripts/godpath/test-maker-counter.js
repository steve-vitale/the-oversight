#!/usr/bin/env node
'use strict';
const fs = require('fs'), path = require('path');
const K = require('./lib'), T = K.reporter('maker-counter');
const { preserveCounter, make } = require('../policies/livelihood');
(async () => {
  const G = await K.load({ seed: Number(process.env.SEED || 7) }); K.newRun(G);
  const s = G.state.scholar, v = G.state.village;
  s.insideHaven = true; s.kcal = 4000;
  G.state.codex.techniques = { cook: true, preserve: true, render: false, shell: true, clean: true };
  const meal = () => ({ name: 'Prepared cooked fish', plantId: 'meat_fish', foodKind: 'meat', foodState: 'cooked', units: 4, kcalEach: 400, safe: true, edible: true, spoilDay: s.day + 2, kg: 0.2 });
  let stash = G.prepStash(); stash.push(meal());
  const pack = JSON.stringify(s.inventory), ctx = {}, ticks = s.dayTicks;
  make(G, ctx);
  T.ok('maker smokes and shelves actual counter food with 16 paid ticks', ctx.livelihoodCounterPreserves === 1 && ctx.livelihoodCounterStored === 1 && s.dayTicks === ticks + 16 && !stash.length && v.pantry.some(i => i.foodState === 'preserved'));
  T.ok('personal meal buffer is untouched', JSON.stringify(s.inventory) === pack && s.kcal === 4000);
  stash.push(meal()); const again = s.dayTicks; preserveCounter(G, ctx);
  T.ok('repeated upkeep does not run the counter twice in one day', s.dayTicks === again && stash.length === 1);
  const before = () => JSON.stringify({ stash: s.prepStash, pantry: v.pantry, ticks: s.dayTicks, kcal: s.kcal });
  let snap = before(); s.kcal = 1000; snap = before(); preserveCounter(G, {});
  T.ok('a hungry maker keeps their action reserve', before() === snap); s.kcal = 4000;
  s.dayTicks = 400; snap = before(); preserveCounter(G, {});
  T.ok('late day work is deferred without paying or consuming', before() === snap); s.dayTicks = 0;
  stash.length = 0; const bad = meal(); bad.parasiteRisk = { id: 'trichinosis', p: 1 }; stash.push(bad);
  snap = before(); preserveCounter(G, {});
  T.ok('unresolved parasite risk cannot be smoked and laundered into pantry', before() === snap);
  stash.length = 0; const raw = meal(); raw.foodState = 'cleaned'; raw.diseaseRisk = { p: 0.35, dmg: 12 }; raw.parasiteRisk = { id: 'trichinosis', p: 1 }; stash.push(raw);
  const rawCtx = {}; preserveCounter(G, rawCtx);
  T.ok('cleaned meat first pays the real cooking action', rawCtx.livelihoodCounterCooks === 1 && raw.foodState !== 'cleaned');
  T.ok('only cooked-through parasite-free food reaches the pantry', !rawCtx.livelihoodCounterStored || (!raw.undercooked && !raw.parasiteRisk && !raw.diseaseRisk));
  stash.length = 0; const poison = meal(); poison.name = 'Prepared poison'; poison.poisonRisk = { p: 1, dmg: 50 }; stash.push(meal(), poison);
  const mixed = {}; preserveCounter(G, mixed);
  T.ok('bulk shelving does not feed a dangerous neighboring batch', mixed.livelihoodCounterPreserves === 1 && !mixed.livelihoodCounterStored && stash.includes(poison) && !v.pantry.some(i => i.name === poison.name));
  stash.length = 0; stash.push(meal()); G.map.px = 0; G.map.py = 0; s.insideHaven = false; G.state.systemArrived = false; s.integration = 0;
  snap = before(); G.putAwayFinished();
  T.ok('public put-away refuses remote hands without mutating stock', before() === snap);
  stash.length = 0; stash.push(meal());
  G.map.px = v.px ?? 4; G.map.py = v.py ?? 4; s.insideHaven = true; s.exiled = true;
  snap = before(); G.putAwayFinished();
  T.ok('public put-away honors exile just like Donate', before() === snap); s.exiled = false;
  G.putAwayFinished();
  T.ok('public put-away still shelves inside the hall', stash.length === 0);
  stash.push(meal()); G.map.px = 0; G.map.py = 0; s.insideHaven = false;
  G.state.systemArrived = true; s.integration = 100;
  T.ok('prepared Full Integration has real remote stores access', G.havenStoresAccess() === 'remote');
  G.putAwayFinished();
  T.ok('earned remote-access contract still permits public shelving', stash.length === 0);
  G.map.px = v.px ?? 4; G.map.py = v.py ?? 4; s.insideHaven = true;
  const options = G.howFarOptions(meal());
  T.ok('cooked counter meat exposes the existing smoke decision and real price', options.some(o => o.id === 'smoke' && /16 ticks/.test(o.detail)));
  const under = meal(); under.undercooked = true;
  T.ok('undercooked counter meat can be finished with a public cook action', G.howFarOptions(under).some(o => o.id === 'cook'));
  const src = K.readSrc('src/js/app.js');
  const start = src.indexOf('  function stashActionsHtml('), end = src.indexOf('\n  }', start) + 4;
  const render = new Function('Game', 'esc', src.slice(start, end) + '\nreturn stashActionsHtml;')(G, String);
  T.ok('the shipped counter renderer binds Smoke for already cooked meat', /data-stash-smoke/.test(render(meal(), 0)));
  T.done();
})().catch(e => { console.error(e); process.exitCode = 1; });
