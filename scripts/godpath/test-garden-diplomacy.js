'use strict';
const K=require('./lib'),D=require('../policies/garden-diplomacy'),{gameplayHash}=require('../gear-usage-audit');
const T=K.reporter('Garden diplomacy controller');
(async()=>{
 const G=await K.load({seed:42});K.newRun(G);
 const ctx={},s=G.state.scholar,ov=G.state.otherVillages[0];
 const plot={};G.gardenPlant(plot,'dandelion',s.day);G.map.tiles[4][4].plots=[plot];
 s.health=100;s.kcal=2400;s.dayTicks=0;G.pendingEncounter=false;G.tbfight=null;
 G.catchUpSim(ov);G.markSeen(ov.x,ov.y,'visited');
 const available=D.targets(G,ctx);
 T.ok('known generated village is a candidate',available.some(v=>v.id===ov.id));
 T.ok('unseen generated villages cannot be selected',available.every(v=>!!G.mapSeen(v.x,v.y)));
 const actions=[{id:'deal_split'},{id:'deal_tribute'}],card={sub:'they know your face',actions};
 T.ok('ambiguous10-29 trust tier cannot authorize a split',D.choose(card,0,1)===null);
 T.ok('trusted public tier authorizes an offered split',D.choose({...card,sub:'they trust you'},0,20)?.id==='deal_split');
 T.ok('missing offered action cannot be invented',D.choose({...card,sub:'they trust you',actions:[]},999999,1)===null);
 T.ok('tribute retains three community meals per person',D.choose(card,16399,2)===null&&D.choose(card,16400,2)?.id==='deal_tribute');
 s.health=20;let before=gameplayHash(G.state);T.ok('reserve refusal is free',!D.visit(G,ctx)&&before===gameplayHash(G.state));s.health=100;
 s.dayTicks=129;T.ok('late-day work cannot start a trip',D.guard(G,ctx)==='late');s.dayTicks=0;
 G.map.px=ov.x;G.map.py=ov.y;s.insideHaven=false;s.mx=4;s.my=4;
 ov.trust=40;ov.commons={strainUs:10,strainThem:10,tension:80,deal:null,depleteMult:1,strainTiles:[],rumorStage:0};
 G.state.village.pantry=[];G.stockPantry(10000,'Prepared diplomacy test');
 const original=G.villageCardAction,pantry=G.pantryKcalLive(G.state.village),ticks=s.dayTicks;
 T.ok('actual visit resolves an offered split',D.visit(G,ctx)&&ov.commons.deal==='split');
 const receipt=ctx.gardenDiplomacy.at(-1);
 T.ok('the real paid conversation and offered actions are recorded',receipt.actions.map(a=>a.id).join(',')==='talk,territory,deal_split'&&s.dayTicks>ticks);
 T.ok('split does not debit pantry and methods stay intact',G.pantryKcalLive(G.state.village)===pantry&&G.villageCardAction===original);
 before=gameplayHash(G.state);T.ok('weekly budget prevents repeated same-day work',!D.visit(G,ctx)&&before===gameplayHash(G.state)&&ctx.gardenDiplomacy.length===1);
 T.ok('receipt includes actual arrival and outcome',receipt.arrival.world[0]===ov.x&&receipt.reason==='returned'&&receipt.after.bearer===G.villagerId);
 plot.dead=true;T.ok('no live garden means no diplomacy expedition',D.guard(G,{})==='no-live-garden');
 T.ok('old arms remain explicit beside the new water-safe arm',D.profiles.map(p=>p.id).join(',')==='garden-diplomacy-control,garden-diplomacy-visit,garden-diplomacy-water-safe');
 plot.dead=false;s.dayTicks=0;s.health=100;s.kcal=2400;s.hydration=0;s.water=[];
 before=gameplayHash(G.state);const dry={};
 T.ok('zero-water optional visit refuses without changing Game',!D.visit(G,dry,true)&&before===gameplayHash(G.state)&&!dry.gardenDiplomacyAttemptDay);
 T.ok('refusal records the actual missing hydration',dry.gardenWaterDecisions[0].water.hydration===0&&dry.gardenWaterDecisions[0].water.reason==='hydration');
 s.hydration=100;s.water=[{liters:1,quality:'dirty'}];
 T.ok('dirty carried water cannot fund optional travel',D.guard(G,{},true)==='water-reserve');
 s.water=[{liters:.5,quality:'clean'}];T.ok('partial clean water retains its actual volume',D.waterStatus(G).reason==='clean-water'&&D.waterStatus(G).cleanLiters===.5);
 s.water=[{liters:1,quality:'clean'}];s.hydration=69;T.ok('hydration threshold has a real boundary',D.guard(G,{},true)==='water-reserve');s.hydration=70;
 T.ok('a hydrated bearer with real clean water may depart',D.guard(G,{},true)===null);
 ov.commons.deal=null;ov.commonsTalkOpen=false;ov.lastTalkDay=null;ov.trust=40;s.hydration=100;
 const safe={};T.ok('safe actual paid visit still reaches its real split',D.visit(G,safe,true)&&ov.commons.deal==='split');
 T.ok('every safe offered action records sufficient visible reserves',safe.gardenDiplomacy[0].actions.every(a=>a.before.water.hydration>=70&&a.before.water.cleanLiters>=1));
 T.done();
})().catch(e=>{console.error(e.stack);process.exitCode=1;});
