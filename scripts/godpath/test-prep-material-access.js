#!/usr/bin/env node
'use strict';
const fs = require('fs'), path = require('path');
const K = require('./lib'), T = K.reporter('prep-material-access');
// This contract checks material routing, not the independent 85% craft roll.
const successfulCraftRoll = fn => { const old = Math.random; Math.random = () => 0.1; try { return fn(); } finally { Math.random = old; } };
(async () => {
  const G = await K.load({ seed: Number(process.env.SEED || 7) }); K.newRun(G);
  const s = G.state.scholar, v = G.state.village;
  s.insideHaven = true; s.kcal = 4000; s.abilities = [];
  G.state.codex.techniques = { clean: true, cook: true, preserve: false, render: false, shell: true };
  s.inventory = [{ itemId: 'stone_knife', units: 1, kg: 0.4 }, { material: 'vine', name: 'Vine', units: 1, kg: 0.1 }];
  const stash = G.prepStash(); stash.length = 0;
  const animal = G.data.animals.find(a => (a.butcher || {}).hide > 0 && !(a.butcher || {}).fat);
  if (!animal) throw new Error('No real hide-bearing animal');
  for (let n = 0; n < 2; n++) stash.push({ plantId: 'meat_' + animal.id, animalId: animal.id, name: 'Prepared carcass', foodKind: 'meat', foodState: 'carcass', units: 1, hiddenKcal: 1000, kcalEach: 0, kg: 1, spoilDay: s.day + 2 });
  G.cleanCarcass(undefined, stash);
  T.ok('actual butchering leaves hides on the counter rather than silently in pockets', stash.some(i => i.material === 'hide') && G.materialCount('hide') === 0);
  const exists = typeof G.takePrepMaterial === 'function';
  T.ok('there is a public deliberate counter material pickup', exists);
  const take = (i, n) => exists ? G.takePrepMaterial(i, n) : null;
  const src = K.readSrc('src/js/app.js');
  const start = src.indexOf('  function stashActionsHtml('), end = src.indexOf('\n  }', start) + 4;
  const render = new Function('Game', 'esc', src.slice(start, end) + '\nreturn stashActionsHtml;')(G, String);
  T.ok('the actual counter renderer offers the current wired material pickup', /data-stash-takemat/.test(render(stash.find(i => i.material === 'hide'), 0)));
  const ticks = s.dayTicks;
  for (const it of stash.filter(i => i.material === 'hide').slice(0, 2)) take(stash.indexOf(it), 1);
  T.ok('two deliberate pickups fund the real carried recipe and cost four ticks', G.materialCount('hide') === 2 && s.dayTicks === ticks + 4);
  G.state.codex.recipes.hide_armor = { level: 3 }; // explicit prepared knowledge, not natural learning
  const crafted = successfulCraftRoll(() => G.craft('hide_armor')), armor = s.inventory.findIndex(i => i.itemId === 'hide_armor');
  if (armor >= 0) G.equip(armor, 'torso');
  T.ok('recovered actual byproducts craft and equip through normal public actions', crafted === true && (s.equipped.torso || {}).itemId === 'hide_armor' && G.materialCount('hide') === 0 && G.materialCount('vine') === 0);
  const material = units => ({ material: 'hide', name: 'Prepared hide', units, kg: 1, kcalEach: 0, spoilDay: 9999, sourceTag: 'preserve-me' });
  const snapshot = () => JSON.stringify({ pack: s.inventory, counter: stash, ticks: s.dayTicks, trust: v.trust });
  stash.length = 0; stash.push(material(5)); s.water = [{ liters: 2 }];
  s.inventory = [{ name: 'Prepared ballast', units: 1, kg: G.carryLimit() - 4.5 }];
  let beforeTicks = s.dayTicks; take(0, 5);
  T.ok('pickup takes only what fits including carried water', s.inventory.some(i => i.material === 'hide' && i.units === 2) && stash[0].units === 3 && G.packWeight() <= G.carryLimit() && s.dayTicks === beforeTicks + 2);
  T.ok('split material retains its actual metadata', (s.inventory.find(i => i.material === 'hide') || {}).sourceTag === 'preserve-me');
  s.inventory = [{ name: 'Prepared full pack', units: 1, kg: G.carryLimit() }]; s.water = [];
  let before = snapshot(); take(0, 1);
  T.ok('full pack refusal preserves stock, time and trust', snapshot() === before);
  s.inventory = []; stash.length = 0; stash.push(material(0)); before = snapshot(); take(0);
  T.ok('explicit empty material cannot become a singleton', snapshot() === before);
  stash[0] = material(2); before = snapshot(); for (const qty of [0, -1, NaN, Infinity]) take(0, qty);
  T.ok('invalid quantities do not consume or create stock', snapshot() === before);
  stash[0] = material(Infinity); before = snapshot(); take(0, 1);
  T.ok('nonfinite source stock cannot fund real material', snapshot() === before);
  stash[0] = { name: 'Prepared food', foodKind: 'meat', foodState: 'cooked', units: 1, kcalEach: 400 }; before = snapshot(); take(0);
  T.ok('material pickup cannot bypass food processing or move arbitrary items', snapshot() === before);
  stash[0] = material(2); G.map.px = 0; G.map.py = 0; s.insideHaven = false;
  before = snapshot(); take(0, 1);
  T.ok('a counter cannot be reached from ordinary wilderness', snapshot() === before);
  G.state.camp = { px: 0, py: 0, condition: 'shitty' }; take(0, 1);
  T.ok('the existing private camp counter supports material collection', s.inventory.some(i => i.material === 'hide' && i.units === 1) && stash[0].units === 1);
  s.inventory = []; stash[0] = material(undefined); take(0);
  T.ok('legacy singleton material stays one actual unit', s.inventory.length === 1 && s.inventory[0].units === 1 && stash.length === 0);
  G.map.px = v.px ?? 4; G.map.py = v.py ?? 4; s.insideHaven = true;
  s.inventory = [{ material: 'vine', units: 1, kg: 0.1 }]; s.equipped.torso = null;
  stash.length = 0; stash.push(material(1), material(1));
  const ctx = {}; successfulCraftRoll(() => require('../policies/livelihood').make(G, ctx));
  T.ok('actual maker routine fetches just missing known recipe stock and crafts it', ctx.livelihoodMaterialUnits === 2 && ctx.livelihoodMaterialTakes === 2 && ctx.livelihoodCrafts === 1 && s.inventory.some(i => i.itemId === 'hide_armor'));
  stash.push(material(2)); G.over = true; before = snapshot(); take(0, 1);
  T.ok('a finished run cannot collect materials', snapshot() === before); G.over = false;
  K.fight(G, 'hushwolf', { px: 2, py: 4, mx: 4, my: 4 }); before = snapshot(); take(0, 1);
  T.ok('a live fight cannot become a free material pickup', snapshot() === before && !!G.tbfight && !G.tbfight.over);
  T.done();
})().catch(e => { console.error(e); process.exitCode = 1; });
