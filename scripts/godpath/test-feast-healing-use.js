'use strict';
// Prepared runtime proof: real paid wound care must spend only power that lands.
const K = require('./lib'), T = K.reporter('feast-healing-use');
(async () => {
  const memory = new Map();
  globalThis.localStorage = {getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,String(v)),removeItem:k=>memory.delete(k),key:i=>[...memory.keys()][i]??null,get length(){return memory.size;}};
  const G = await K.load({ seed: Number(process.env.SEED || 12) });
  function ready(hp = 40) {
    K.newRun(G);
    const s = G.state.scholar;
    s.health = hp; s.kcal = 2400;
    G.learnSkill('wound_care', 2, 'prepared treatment proof');
    s.prog = s.prog || {}; s.prog.feastSurge = 1.5;
    G.grantFeastBuff({ quality: 1, served: [{ itemId: 'foraged_food', kcal: 1800 }], guests: ['a', 'b', 'c'] });
    G.driveOffFeastDraw();
    return s;
  }
  let s = ready(), before = s.kcal;
  T.ok('prepared wound care is known without a magic slot', G.hasAbility('field_medicine') && !(s.abilities || []).some(a => a.id === 'field_medicine'));
  T.ok('grant and declining scavenger do not earn food-use credit', !s.prog.feastSurgeUsed && !s.feastBuff.used && !!s.prog.feastSurge);
  G.activateAbility('field_medicine');
  T.ok('noncombat treatment lands its real 20 HP plus authored 10 HP feast bonus', !G.inCombat() && s.health === 70, s.health);
  T.ok('treatment pays food and the real day-part allowance', s.kcal < before && s.fieldMedDayPart === `${s.day}-${G.dayPart}`);
  T.ok('landed noncombat feast healing earns the food-use deed and spends devotion', s.prog.feastSurgeUsed === true && s.feastBuff.used && s.prog.feastSurge === false);
  const saved = JSON.parse(JSON.stringify(s.feastBuff));
  G.activateAbility('field_medicine');
  T.ok('refused repeated treatment grants no further healing or new receipt', s.health === 70 && JSON.stringify(s.feastBuff) === JSON.stringify(saved));
  s = ready(G.maxHealth());
  G.activateAbility('field_medicine');
  T.ok('full-health treatment grants no bonus or credit', !s.prog.feastSurgeUsed && !s.feastBuff.used && !!s.prog.feastSurge);
  s = ready(G.maxHealth() - 20);
  G.activateAbility('field_medicine');
  T.ok('ordinary healing that leaves no room for the bonus does not spend feast power', s.health === G.maxHealth() && !s.prog.feastSurgeUsed && !s.feastBuff.used);
  s = ready(); s.kcal = 0;
  G.activateAbility('field_medicine');
  T.ok('starving refusal has no heal, cooldown or food-use credit', s.health === 40 && !s.fieldMedDayPart && !s.prog.feastSurgeUsed);
  s = ready(); s.day = s.feastBuff.untilDay;
  G.activateAbility('field_medicine');
  T.ok('expired feast gives ordinary treatment only and no deed', s.health === 60 && !s.prog.feastSurgeUsed);
  s = ready();
  K.giveAbility(G, 'game_sense');
  G.useAbility('game_sense', 'read_sign');
  T.ok('unrelated successful noncombat action still spends no feast devotion', !s.prog.feastSurgeUsed && !s.feastBuff.used);
  s = ready();
  const ctx = {};
  require('../policies/livelihood').care(G, ctx);
  T.ok('caregiver uses its learned visible treatment on real wounds', ctx.livelihoodTreatments === 1 && s.prog.feastSurgeUsed === true);
  s = ready(); s.kcal = 1100;
  const reserve = {};
  require('../policies/livelihood').care(G, reserve);
  T.ok('caregiver reserves dinner instead of spending its low food balance', !reserve.livelihoodTreatments && !s.prog.feastSurgeUsed);
  s = ready(); s.health = G.maxHealth() - 25;
  G.activateAbility('field_medicine');
  T.ok('clamped bonus records only the five HP that actually landed', s.health === G.maxHealth() && s.feastBuff.use.bonusHp === 5);
  s = ready();
  const description = G.activatableAbilities().find(a => a.id === 'field_medicine').desc;
  const messages = [], say = G.say;
  G.say = function(line){messages.push(String(line));return say.apply(this,arguments);};
  const foodBefore = s.kcal;
  G.activateAbility('field_medicine');
  T.ok('visible full treatment price equals its actual 140 kcal charge', /\(140 kcal\)/.test(description) && foodBefore - s.kcal === 140, description);
  G.say = say;
  T.ok('the final actual treatment notice reports the whole unchanged bill', /−140 kcal/.test(messages.at(-1)), messages.at(-1));
  s = ready();
  K.fight(G, 'hushwolf');
  const clock = Date.now;
  let clockCalls = 0, saveCalls, useCalls;
  Date.now = () => { clockCalls++; return clock(); };
  try {
    G.save(); saveCalls = clockCalls;
    clockCalls = 0;
    G.noteFeastedCombatUse(); useCalls = clockCalls;
  } finally { Date.now = clock; }
  T.ok('combat credit adds no diagnostic clock reads beyond its existing save', s.feastBuff.use.kind === 'combat' && useCalls === saveCalls, `${useCalls} vs ${saveCalls}`);
  s = ready();
  const owner = G.villagerId;
  G.activateAbility('field_medicine');
  const use = JSON.stringify(s.feastBuff.use), key = G.state.runKey;
  T.ok('landed healing belongs to the actual bearer', s.prog.feastSurgeBy === 'p' && s.feastBuff.use.kind === 'healing');
  T.ok('real Continue preserves the landed healing receipt and personal credit', G.load(key) && G.villagerId === owner && JSON.stringify(G.state.scholar.feastBuff.use) === use && G.state.scholar.prog.feastSurgeBy === 'p');
  s = ready();
  const companion = G.state.village.roster.find(id => id !== G.villagerId && G.npcAge(id) >= 18);
  G.state.village.party = [companion];
  K.fight(G, 'hushwolf', {party:true});
  const enemy = G.tbfight.fighters.find(f => f.kind === 'monster'), ally = G.tbfight.fighters.find(f => f.villagerId === companion);
  if (!ally || !enemy) throw Error('Prepared actual party actor absent');
  enemy.hp = enemy.maxHp = 10000;
  G.tbDamage(enemy.key, 1, 'strike', ally.key, {undodgeable:true});
  T.ok('actual companion damage preserves Muse first-blow feast ownership', enemy.hp < 10000 && s.prog.feastSurgeBy === 'v:' + companion && s.feastBuff.use.kind === 'combat');
  const credited = JSON.stringify(s.feastBuff.use);
  G.tbDamage(enemy.key, 1, 'strike', 'p', {undodgeable:true});
  T.ok('a later actual bearer hit cannot steal or repeat companion credit', s.prog.feastSurgeBy === 'v:' + companion && JSON.stringify(s.feastBuff.use) === credited);
  T.done();
})().catch(e => { console.error(e.stack); process.exitCode = 1; });
